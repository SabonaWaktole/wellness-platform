/**
 * Which Support page each router path belongs to, or why it has none.
 *
 * Patterns are the router's own `path` strings: top level paths as written
 * (`/login`, `/admin/tenants`), and the tenant shell's children relative to
 * `/:tenantSlug` (`clients/:clientId`; the empty string is the shell's index
 * route). `routeMap.test.ts` walks the real router and fails when a route is
 * neither mapped nor excluded, so a new route cannot ship without deciding
 * its Support status.
 *
 * Order matters: where two patterns can match one URL, the specific one comes
 * first (`clients/new` before `clients/:clientId`).
 */
export interface RouteMapEntry {
  pattern: string;
  /** The page's guide id, or null for an excluded route. */
  pageId: string | null;
  /** Required when `pageId` is null. */
  reason?: string;
  /** The page id is `<pageId>.<variant>`, published by the page (the role dashboards). */
  variants?: boolean;
}

